-- 火兔复刻 v2：首页批次数据表
-- banner 轮播
CREATE TABLE IF NOT EXISTS ht_banner (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  image VARCHAR(255) NOT NULL DEFAULT '' COMMENT '图片路径',
  url VARCHAR(255) NOT NULL DEFAULT '' COMMENT '跳转链接',
  url_type TINYINT NOT NULL DEFAULT 1 COMMENT '链接类型',
  is_show TINYINT NOT NULL DEFAULT 1 COMMENT '是否显示',
  createtime BIGINT NOT NULL DEFAULT 0,
  KEY idx_show (is_show)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='首页轮播';

-- 公告
CREATE TABLE IF NOT EXISTS ht_affiche (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  title VARCHAR(255) NOT NULL DEFAULT '' COMMENT '公告标题',
  affiche_type VARCHAR(20) NOT NULL DEFAULT '官方' COMMENT '公告类型',
  type VARCHAR(10) NOT NULL DEFAULT '1',
  url VARCHAR(255) NOT NULL DEFAULT '',
  is_show TINYINT NOT NULL DEFAULT 1,
  createtime BIGINT NOT NULL DEFAULT 0,
  KEY idx_show (is_show)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='公告';

-- 藏品（发售日历商品）
CREATE TABLE IF NOT EXISTS ht_goods (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(100) NOT NULL DEFAULT '' COMMENT '藏品名称',
  listimg VARCHAR(255) NOT NULL DEFAULT '' COMMENT '列表图',
  price DECIMAL(10,2) NOT NULL DEFAULT 0 COMMENT '起步价',
  total_num INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '发行总量',
  release_time BIGINT NOT NULL DEFAULT 0 COMMENT '开售时间',
  end_time BIGINT NOT NULL DEFAULT 0 COMMENT '结束时间',
  type VARCHAR(20) NOT NULL DEFAULT 'collection' COMMENT '类型',
  goods_type VARCHAR(10) NOT NULL DEFAULT '2',
  sale_status TINYINT NOT NULL DEFAULT 1 COMMENT '1即将开售 2已开售',
  publisher_name VARCHAR(50) NOT NULL DEFAULT '' COMMENT '发行方',
  publisher_logo VARCHAR(255) NOT NULL DEFAULT '' COMMENT '发行方logo',
  hotnum INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '成交量(热榜)',
  min_price DECIMAL(10,2) NOT NULL DEFAULT 0 COMMENT '市场最低价(热榜)',
  reprice_limit DECIMAL(10,2) NOT NULL DEFAULT 0 COMMENT '寄售限价',
  flux INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '流通量',
  is_show TINYINT NOT NULL DEFAULT 1,
  createtime BIGINT NOT NULL DEFAULT 0,
  KEY idx_sale (sale_status, is_show)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='藏品';
